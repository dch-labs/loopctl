//! Tool dispatch middleware pipeline.
//!
//! Each middleware wraps the dispatch call and can inspect/modify the request before
//! execution and the result after execution.
//!
//! # Architecture
//!
//! ```text
//! [outer middleware .dispatch()]
//!   → pre-processing (inspect/modify context)
//!   → next.dispatch(ctx)
//!     → [inner middleware .dispatch()]
//!       → ...
//!       → [Innermost: ToolCallMiddleware → Tool::call()]
//!       → ...
//!   → post-processing (inspect/modify result)
//!   → return ToolDispatchResult
//! ```
//!
//! # Provided Middlewares
//!
//! | Middleware                | Description                                                       |
//! |---------------------------|-------------------------------------------------------------------|
//! | [`ToolCallMiddleware`]    | Innermost layer — looks up tool in registry, calls `Tool::call()` |
//! | [`PermissionMiddleware`]  | Checks [`PermissionCheck`] before execution                       |
//! | [`TimeoutMiddleware`]     | Wraps execution in a deadline with retry                          |
//! | [`UnknownToolMiddleware`] | Suggests closest matching tool on "not found"                     |
//!
//! # Example
//!
//! ```rust,ignore
//! use loopctl::engine::middleware::{
//!     ToolPipeline, ToolCallMiddleware, PermissionMiddleware, TimeoutMiddleware,
//! };
//! use loopctl::tool::ToolRegistry;
//! use std::sync::Arc;
//!
//! let registry = Arc::new(ToolRegistry::new());
//!
//! let pipeline = ToolPipeline::builder()
//!     .with(PermissionMiddleware::deny_all())
//!     .with(TimeoutMiddleware::from_secs(120))
//!     .core(registry)
//!     .build()
//!     .expect("pipeline configuration is valid");
//!
//! let result = pipeline.invoke(ctx).await;
//! ```

