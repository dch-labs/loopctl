// ===================================================
// Dispatch context and result
// ===================================================

/// Context passed through the middleware chain for a single tool invocation.
///
/// Built once per tool call by the framework, then threaded through each
/// middleware. Middlewares can read from and write to this struct.
///
/// # Fields
///
/// - [`tool_name`](ToolDispatchContext::tool_name) — Which tool is being called.
/// - [`input`](ToolDispatchContext::input) — The JSON input to the tool.
/// - [`call_id`](ToolDispatchContext::call_id) — Unique ID for this tool call.
/// - [`turn_number`](ToolDispatchContext::turn_number) — Turn number within the session.
/// - [`cancel`](ToolDispatchContext::cancel) — Shared cancellation signal.
/// - [`permission`](ToolDispatchContext::permission) — Permission state for this call.
/// - [`tool_context`](ToolDispatchContext::tool_context) — Context passed to the tool.
///
/// Session identity is available via [`tool_context.session_id`](ToolContext::session_id)
/// rather than duplicated on this struct.
pub struct ToolDispatchContext {
    /// Which tool is being called.
    ///
    /// Set by the framework from the model's tool call part.
    /// Middlewares can redirect to a different tool by modifying
    /// this field (e.g. a routing middleware).
    pub tool_name: String,

    /// The JSON input to the tool.
    ///
    /// The raw JSON value from the model's tool call part.
    /// Middlewares can inspect or transform this before the tool
    /// is invoked (e.g. sanitisation, validation, schema upgrade).
    pub input: Value,

    /// Unique ID for this tool call.
    ///
    /// Generated by the model provider and used to correlate tool
    /// results back to the originating tool call request.
    pub call_id: String,

    /// Turn number within the session.
    ///
    /// Monotonically increasing counter for the current conversation
    /// turn. Useful for logging and for middlewares that need to
    /// enforce per-turn limits.
    pub turn_number: usize,

    /// Shared cancellation signal — middlewares should check this
    /// before doing expensive work.
    ///
    /// Set by the framework when the user or a deadline triggers
    /// cancellation. Long-running middlewares (e.g. [`TimeoutMiddleware`])
    /// should cooperative-check this via `tokio::select!`.
    pub cancel: Arc<CancelSignal>,

    /// Permission state for this call.
    ///
    /// Set by the framework based on tool registration. Middlewares
    /// (e.g. [`PermissionMiddleware`]) can read and modify this.
    pub permission: PermissionCheck,

    /// Context passed to the underlying tool invocation.
    ///
    /// Middlewares can augment this (e.g. adding metadata) before
    /// the innermost [`ToolCallMiddleware`] invokes `Tool::call()`.
    pub tool_context: ToolContext,
}
