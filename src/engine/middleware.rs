/// Builds an ordered middleware pipeline for tool dispatch.
///
/// # Example
///
/// ```rust,ignore
/// let pipeline = ToolPipeline::builder()
///     .with(PermissionMiddleware::deny_all())
///     .with(TimeoutMiddleware::from_secs(120))
///     .core(Arc::new(tool_registry))
///     .build()
///     .expect("pipeline configuration is valid");
/// ```
pub struct ToolPipelineBuilder {
    middlewares: Vec<Arc<dyn ToolMiddleware>>,
    core: Option<Arc<ToolRegistry>>,
}

impl ToolPipelineBuilder {
    /// Create a new, empty builder.
    #[must_use]
    pub fn new() -> Self {
        Self {
            middlewares: Vec::new(),
            core: None,
        }
    }

    /// Add a middleware layer to the pipeline.
    ///
    /// Middlewares are executed in the order they are added (outermost first).
    /// The core dispatch is always the innermost layer.
    #[must_use]
    pub fn with<M: ToolMiddleware + 'static>(mut self, middleware: M) -> Self {
        self.middlewares.push(Arc::new(middleware));
        self
    }

    /// Add an already-`Arc`-wrapped middleware.
    ///
    /// Useful when the same middleware instance needs to be shared
    /// across multiple pipelines.
    #[must_use]
    pub fn with_arc(mut self, middleware: Arc<dyn ToolMiddleware>) -> Self {
        self.middlewares.push(middleware);
        self
    }

    /// Set the core tool registry for the pipeline.
    ///
    /// The registry is wrapped in a [`ToolCallMiddleware`] that performs
    /// the actual tool lookup and invocation. This is the innermost
    /// layer of the pipeline.
    #[must_use]
    pub fn core(mut self, registry: Arc<ToolRegistry>) -> Self {
        self.core = Some(registry);
        self
    }

    /// Build the pipeline.
    ///
    /// # Errors
    ///
    /// Returns [`PipelineError::MissingCore`] if no core registry was provided.
    pub fn build(self) -> Result<ToolPipeline, PipelineError> {
        let registry = self.core.ok_or(PipelineError::MissingCore)?;
        Ok(ToolPipeline {
            middlewares: self.middlewares.into(),
            core: Arc::new(ToolCallMiddleware::new(registry)),
            index: 0,
        })
    }
}

impl Default for ToolPipelineBuilder {
    fn default() -> Self {
        Self::new()
    }
}

// ===================================================
// ToolCallMiddleware (innermost core)
// ===================================================

/// The innermost middleware that performs the actual tool invocation.
///
/// Looks up the tool by name in the [`ToolRegistry`], calls
/// [`crate::tool::Tool::call()`], and converts the result into a
/// [`ToolDispatchResult`]. If the tool is not found, produces a
/// soft error result (not a hard error) so the model can recover.
///
/// This middleware is automatically created by the pipeline builder
/// and always occupies the innermost position in the chain.
pub struct ToolCallMiddleware {
    registry: Arc<ToolRegistry>,
}

impl ToolCallMiddleware {
    const NAME: &str = "tool_call";

    /// Create a new core dispatch wrapping the given registry.
    #[must_use]
    pub fn new(registry: Arc<ToolRegistry>) -> Self {
        Self { registry }
    }

    /// Execute the tool call — the terminal dispatch.
    ///
    /// Looks up the tool by name in the registry, calls `Tool::call()`,
    /// and converts the result. This is not a middleware — it has no
    /// `next` parameter because there is nothing to chain to.
    fn dispatch(
        &self,
        ctx: &mut ToolDispatchContext,
    ) -> Pin<Box<dyn Future<Output = ToolDispatchResult> + Send + '_>> {
        let tool_name = ctx.tool_name.clone();
        let input = ctx.input.clone();
        let tool_ctx = ctx.tool_context.clone();
        let registry = Arc::clone(&self.registry);
        let cancel = Arc::clone(&ctx.cancel);

        Box::pin(async move {
            let start = Instant::now();
            let Some(tool) = registry.get(&tool_name) else {
                let available: Vec<String> = registry.tool_names();
                let available_refs: Vec<&str> = available.iter().map(String::as_str).collect();
                let error = AgentError::tool_not_found(&tool_name, &available_refs);
                return ToolDispatchResult::err(&tool_name, error.to_string(), start.elapsed());
            };

            let call_result = tokio::select! {
                r = tool.call(input, &tool_ctx) => r,
                () = cancel.notified() => {
                    return ToolDispatchResult::err(
                        &tool_name,
                        format!("Tool '{tool_name}' cancelled"),
                        start.elapsed(),
                    );
                }
            };

            let duration = start.elapsed();
            ToolDispatchResult::from_result(&tool_name, call_result, duration)
        })
    }
}

// ===================================================
// PermissionMiddleware
// ===================================================

/// Permission check function type.
pub type PermissionCheckFn = Arc<dyn Fn(&ToolDispatchContext) -> PermissionCheck + Send + Sync>;

/// Middleware that checks tool permissions before execution.
///
/// Inspects the [`PermissionCheck`] in the dispatch context. If the
/// permission is `Deny`, short-circuits with an error result. If
/// `Ask`, also denies (interactive prompts are outside the framework's
/// scope — agents should handle this themselves).
///
/// # Example
///
/// ```rust,ignore
/// // Deny all by default
/// let mw = PermissionMiddleware::deny_all();
///
/// // Custom logic
/// let mw = PermissionMiddleware::with_check(|ctx| {
///     if ctx.tool_name == "safe_read" {
///         PermissionCheck::Allow
///     } else {
///         PermissionCheck::Deny
///     }
/// });
/// ```
pub struct PermissionMiddleware {
    /// Override function for permission checking.
    ///
    /// When `Some`, this function is called to determine the permission
    /// for each dispatch. When `None`, the middleware reads
    /// [`ToolDispatchContext::permission`] directly.
    check_fn: Option<PermissionCheckFn>,
}

impl PermissionMiddleware {
    /// Create a permission middleware that denies all calls.
    ///
    /// Every tool call will be short-circuited with a permission-denied
    /// error. Useful as a safety default in restricted environments.
    #[must_use]
    pub fn deny_all() -> Self {
        Self {
            check_fn: Some(Arc::new(|_| PermissionCheck::Deny {
                reason: "blocked by policy".into(),
            })),
        }
    }

    /// Create a permission middleware that allows all calls.
    ///
    /// No permission checks are performed — every tool call passes
    /// through to the next layer. This is the runtime-equivalent of
    /// having no permission middleware at all, but it can be useful
    /// for logging or metrics in permissive environments.
    #[must_use]
    pub fn allow_all() -> Self {
        Self {
            check_fn: Some(Arc::new(|_| PermissionCheck::Allow)),
        }
    }

    /// Create a permission middleware with a custom check function.
    ///
    /// The function receives a reference to the dispatch context and
    /// returns the appropriate [`PermissionCheck`] for that call.
    pub fn with_check(
        f: impl Fn(&ToolDispatchContext) -> PermissionCheck + Send + Sync + 'static,
    ) -> Self {
        Self {
            check_fn: Some(Arc::new(f)),
        }
    }

    /// Create a permission middleware that reads from the context.
    ///
    /// The middleware reads `ctx.permission` directly, without
    /// applying any override. This is useful when the permission
    /// is set by the framework or a prior middleware.
    #[must_use]
    pub fn from_context() -> Self {
        Self { check_fn: None }
    }

    fn resolve_permission(&self, ctx: &ToolDispatchContext) -> PermissionCheck {
        match &self.check_fn {
            Some(f) => f(ctx),
            None => ctx.permission.clone(),
        }
    }
}

impl ToolMiddleware for PermissionMiddleware {
    fn name(&self) -> &'static str {
        "permission"
    }

    fn dispatch<'a>(
        &'a self,
        ctx: &'a mut ToolDispatchContext,
        next: &'a ToolPipeline,
    ) -> Pin<Box<dyn Future<Output = ToolDispatchResult> + Send + 'a>> {
        let permission = self.resolve_permission(ctx);
        match permission {
            PermissionCheck::Allow => next.dispatch(ctx),
            PermissionCheck::Ask { .. } | PermissionCheck::Deny { .. } => {
                let tool_name = ctx.tool_name.clone();
                let reason = match &permission {
                    PermissionCheck::Deny { reason } => reason.clone(),
                    PermissionCheck::Ask { prompt } => format!("permission required: {prompt}"),
                    _ => "blocked".to_string(),
                };
                tracing::warn!(
                    tool = %tool_name,
                    permission = %reason,
                    "tool call blocked by permission middleware"
                );
                Box::pin(std::future::ready(ToolDispatchResult::err(
                    &tool_name,
                    format!("Permission {reason} for tool '{tool_name}'"),
                    Duration::ZERO,
                )))
            }
            PermissionCheck::Modify { .. } => {
                // Modify is treated as allow — the tool can proceed
                // but the agent might apply modifications to the input.
                next.dispatch(ctx)
            }
        }
    }
}

