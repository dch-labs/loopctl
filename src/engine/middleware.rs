    /// A tool that returns a string of repeated characters for testing
    /// output truncation. The tool name encodes the repeat count as
    /// `long_output_N` where N is the number of characters.
    struct LongOutputTool;

    impl Tool for LongOutputTool {
        fn name(&self) -> &str {
            "long_output"
        }

        fn description(&self) -> &str {
            "Returns a long string for testing"
        }

        fn schema(&self) -> ToolSchema {
            ToolSchema {
                tool: self.name().to_string(),
                description: self.description().to_string(),
                input_schema: serde_json::json!({"type": "object", "properties": {}}),
            }
        }

        fn call(
            &self,
            input: Value,
            _ctx: &ToolContext,
        ) -> Pin<Box<dyn Future<Output = Result<ToolOutput, ToolError>> + Send + '_>> {
            Box::pin(async move {
                let count = input.get("count").and_then(|v| v.as_u64()).unwrap_or(100) as usize;
                let ch = input.get("char").and_then(|v| v.as_str()).unwrap_or("a");
                Ok(ToolOutput::text(ch.repeat(count)))
            })
        }
    }

    /// A tool that returns [`ToolContent::Multipart`] output for testing
    /// that non-text output passes through unchanged.
    struct MultipartTool;

    impl Tool for MultipartTool {
        fn name(&self) -> &str {
            "multipart"
        }

        fn description(&self) -> &str {
            "Returns multipart content"
        }

        fn schema(&self) -> ToolSchema {
            ToolSchema {
                tool: self.name().to_string(),
                description: self.description().to_string(),
                input_schema: serde_json::json!({"type": "object", "properties": {}}),
            }
        }

        fn call(
            &self,
            _input: Value,
            _ctx: &ToolContext,
        ) -> Pin<Box<dyn Future<Output = Result<ToolOutput, ToolError>> + Send + '_>> {
            Box::pin(async move {
                Ok(ToolOutput {
                    payload: ToolContent::Multipart(vec![
                        ToolContentPart::Text {
                            text: "part1".to_string(),
                        },
                        ToolContentPart::Text {
                            text: "part2".to_string(),
                        },
                    ]),
                    is_error: false,
                })
            })
        }
    }

