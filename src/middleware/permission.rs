    /// A resolver that records the ask it saw and answers a fixed resolution.
    ///
    /// The fixture behind every typed-seam pin: the ask is cloned out
    /// before the returned future exists, so a cancel-dropped future
    /// loses no capture, and the fixed answer makes the resolution
    /// under test the test's own choice.
    struct CapturingResolver {
        answer: PermissionResolution,
        seen: Arc<Mutex<Option<PermissionAsk>>>,
    }

    impl PermissionAskResolver for CapturingResolver {
        fn resolve<'a>(
            &'a self,
            ask: &'a PermissionAsk,
        ) -> Pin<Box<dyn Future<Output = PermissionResolution> + Send + 'a>> {
            let seen = PermissionAsk {
                tool_name: ask.tool_name.clone(),
                prompt: ask.prompt.clone(),
                input: ask.input.clone(),
                call_id: ask.call_id.clone(),
                turn_number: ask.turn_number,
                cwd: ask.cwd.clone(),
            };
            let answer = self.answer.clone();
            Box::pin(async move {
                if let Ok(mut guard) = self.seen.lock() {
                    *guard = Some(seen);
                }
                answer
            })
        }
    }

    /// A typed resolver that never answers.
    ///
    /// The pending half of the typed-seam cancel race: its future is
    /// `pending()` forever, so only cancellation can resolve the
    /// dispatch — the arm the pending-approval abort pin drives.
    struct NeverAnsweringResolver;

    impl PermissionAskResolver for NeverAnsweringResolver {
        fn resolve<'a>(
            &'a self,
            _ask: &'a PermissionAsk,
        ) -> Pin<Box<dyn Future<Output = PermissionResolution> + Send + 'a>> {
            Box::pin(std::future::pending())
        }
    }

    /// The capture handle a typed-seam test reads the seen ask through.
    ///
    /// Shared with the resolver, because the resolver itself moves into
    /// the middleware as the trait object — the handle outlives it at
    /// the test's scope.
    type SeenAsks = Arc<Mutex<Option<PermissionAsk>>>;

    /// The dispatch every typed-seam test parks.
    ///
    /// A deploy call whose input, call id, and turn the resolver must
